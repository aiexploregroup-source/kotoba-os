/**
 * Generates src/data/joyo.ts from open data:
 *  - kanji-jouyou.json (KANJIDIC-derived Jōyō subset, EDRDG license)
 *  - kanjidic2.xml.gz  (classical Kangxi radical numbers, EDRDG license)
 *
 * Only open/reference fields are used. WaniKani-derived fields in the source
 * (wk_*) are deliberately ignored so no proprietary lesson content is copied.
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';

const root = process.cwd();
const sourceDir = path.join(root, 'scripts', 'source');
const jouyouSource = path.join(sourceDir, 'kanji-jouyou.json');
const kanjidicSource = path.join(sourceDir, 'kanjidic2.xml.gz');
const target = path.join(root, 'src', 'data', 'joyo.ts');

// The 214 traditional Kangxi radicals, in KANJIDIC's classical numbering.
const KANGXI = '一丨丶丿乙亅二亠人儿入八冂冖冫几凵刀力勹匕匚匸十卜卩厂厶又口囗土士夂夊夕大女子宀寸小尢尸屮山巛工己巾干幺广廴廾弋弓彐彡彳心戈户手支攴文斗斤方无日曰月木欠止歹殳毋比毛氏气水火爪父爻爿片牙牛犬玄玉瓜瓦甘生用田疋疒癶白皮皿目矛矢石示禸禾穴立竹米糸缶网羊羽老而耒耳聿肉臣自至臼舌舛舟艮色艸虍虫血行衣襾見角言谷豆豕豸貝赤走足身車辛辰辵邑酉采里金長門阜隶隹雨靑非面革韋韭音頁風飛食首香馬骨高髟鬥鬯鬲鬼魚鳥鹵鹿麥麻黃黍黑黹黽鼎鼓鼠鼻齊齒龍龜龠';
const radicalChars = Array.from(KANGXI);

const dataset = JSON.parse(fs.readFileSync(jouyouSource, 'utf8'));
const xml = zlib.gunzipSync(fs.readFileSync(kanjidicSource)).toString('utf8');

// literal -> classical radical number
const radicalNumbers = new Map();
for (const block of xml.split('<character>').slice(1)) {
  const literal = block.match(/<literal>([\s\S]*?)<\/literal>/)?.[1];
  const rad = block.match(/<rad_value rad_type="classical">(\d+)<\/rad_value>/)?.[1];
  if (literal && rad) radicalNumbers.set(literal, Number(rad));
}

const toKatakana = (value) =>
  value.replace(/[\u3041-\u3096]/g, (char) => String.fromCharCode(char.charCodeAt(0) + 0x60));

const unique = (values) => [...new Set(values)];

const cleanMeanings = (meanings) =>
  unique(
    meanings
      .filter((value) => !/radical|katakana|hiragana|radix/i.test(value))
      .map((value) => value.trim().toLowerCase())
      .filter(Boolean),
  ).slice(0, 3);

const cleanKun = (readings) =>
  unique(readings.map((value) => value.replace(/[.\-]/g, '').trim()).filter(Boolean)).slice(0, 3);

const cleanOn = (readings) =>
  unique(readings.map((value) => toKatakana(value.trim())).filter(Boolean)).slice(0, 3);

const levelFor = (entry) => {
  const jlpt = entry.jlpt_new ?? entry.jlpt_old;
  return jlpt ? `N${jlpt}` : 'Jōyō';
};

const strokeLabel = (n) => `${n} stroke${n === 1 ? '' : 's'}`;

const hooks = [
  (meaning, radical, strokes) => `Start with ${radical} and build toward “${meaning}”. Trace the ${strokeLabel(strokes)} slowly, then say the meaning aloud.`,
  (meaning, radical, strokes) => `The ${radical} shape anchors this kanji. Picture “${meaning}” as you write its ${strokeLabel(strokes)}.`,
  (meaning, radical, strokes) => `Look for ${radical} inside the character. Connect that shape to “${meaning}” and the ${strokes}-stroke form sticks.`,
  (meaning, radical, strokes) => `A ${strokeLabel(strokes)} kanji built around ${radical}. Hold the image of “${meaning}” while you practise it.`,
];

const entries = Object.entries(dataset).map(([char, entry], index) => {
  const meanings = cleanMeanings(entry.meanings ?? []);
  const meaning = meanings[0] ?? 'kanji';
  const on = cleanOn(entry.readings_on ?? []);
  const kun = cleanKun(entry.readings_kun ?? []);
  const radNumber = radicalNumbers.get(char);
  const radical = radNumber && radicalChars[radNumber - 1] ? radicalChars[radNumber - 1] : char;
  const strokes = entry.strokes || 1;
  const mnemonic = hooks[index % hooks.length](meaning, radical, strokes);

  return { char, meaning: meanings.join(', ') || meaning, kun, on, level: levelFor(entry), radical, strokes, mnemonic, examples: [] };
});

// Deterministic order: elementary grades first, then frequency — stable across regenerations.
entries.sort((a, b) => {
  const ga = dataset[a.char].grade ?? 9;
  const gb = dataset[b.char].grade ?? 9;
  if (ga !== gb) return ga - gb;
  return (dataset[a.char].freq ?? 99999) - (dataset[b.char].freq ?? 99999);
});

const body = entries
  .map((item) => `  { char: '${item.char}', meaning: '${item.meaning.replace(/'/g, "\\'")}', kun: [${item.kun.map((r) => `'${r}'`).join(', ')}], on: [${item.on.map((r) => `'${r}'`).join(', ')}], level: '${item.level}', radical: '${item.radical}', strokes: ${item.strokes}, mnemonic: '${item.mnemonic.replace(/'/g, "\\'")}', examples: [] },`)
  .join('\n');

const output = `// Generated by scripts/import-joyo.mjs from KANJIDIC / Jōyō open data.\n// Do not edit by hand — regenerate with: npm run import:joyo\nimport type { KanjiItem } from '../types';\n\n/** All 2,136 official Jōyō kanji with open-licensed readings, meanings and radicals. */\nexport const joyoKanji: KanjiItem[] = [\n${body}\n];\n`;

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, output);
console.log(`Wrote ${entries.length} Jōyō kanji to ${path.relative(root, target)}`);
